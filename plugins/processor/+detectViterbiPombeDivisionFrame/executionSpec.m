% detectViterbiPombeDivisionFrame.executionSpec  Pipeline contract.

spec = struct();
spec.summary = 'Tracks the pombe cell of interest by Viterbi and writes a mask plus septum profile/score dataseries.';

spec.staticKeys = { ...
    'inputMode','anchorMode','anchorX','anchorY','anchorFrames', ...
    'anchorWeight','distanceWeight','areaWeight','iouWeight', ...
    'maxJumpCellDiameters','minArea','maxArea','minTrackFrames', ...
    'splitAreaDropRatio','hardAreaDropRatio','splitRadiusCellDiameters', ...
    'splitCombinedAreaMinRatio','splitCombinedAreaMaxRatio','stopAtSplit', ...
    'profileBins','profileSmoothBins','profileEdgeIgnoreFraction', ...
    'septumPolarity','septumScoreThreshold','debug'};
spec.outputKeys = {'outputMaskChannelName','profileSeriesName','scoreSeriesName'};
spec.defaultImportKeys = {'instanceChannelName','rawChannelName','outputMaskChannelName'};
spec.defaults = rmfield(detectViterbiPombeDivisionFrame.setparam(struct()), 'tip');

spec.labels = struct( ...
    'instanceChannelName', 'Instance mask channel', ...
    'rawChannelName', 'Raw image channel', ...
    'outputMaskChannelName', 'Tracked cell mask output', ...
    'profileSeriesName', 'Intensity profile dataseries', ...
    'scoreSeriesName', 'Septum score dataseries', ...
    'anchorMode', 'Initial target selector', ...
    'septumPolarity', 'Septum contrast polarity', ...
    'septumScoreThreshold', 'Septum score threshold');

spec.tips = struct( ...
    'instanceChannelName', 'Labeled CellposeSAM instance mask channel, usually results_*_cell.', ...
    'rawChannelName', 'Raw or focused DIC channel used to compute the longitudinal septum profile.', ...
    'outputMaskChannelName', 'Binary ROI image channel for the selected cell of interest.', ...
    'profileSeriesName', 'Temporal dataseries with one row per frame and 100 normalized profile bins by default.', ...
    'scoreSeriesName', 'Temporal dataseries with the frame-wise septum score, binary septum detection, and tracking diagnostics.', ...
    'septumScoreThreshold', 'Threshold applied to septumScore to create the septumDetected output column.');

