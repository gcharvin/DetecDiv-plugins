spec.contract = struct();
spec.contract.in = [ ...
    localPortDef('roiList', 'roiList', true, 'edge'), ...
    localPortDef('channels', 'channelSet', true, 'edge') ...
    ];
spec.contract.out = [ ...
    localPortDef('roiList', 'roiList', true, 'edge'), ...
    localPortDef('channels', 'channelSet', true, 'edge'), ...
    localPortDef('dataSeries', 'dataSeriesSet', true, 'edge') ...
    ];
spec.contract.selectors = struct( ...
    'channelParam', 'instanceChannelName', ...
    'channelsParam', '', ...
    'framesParam', 'frames', ...
    'outputNameParam', 'outputMaskChannelName');
spec.contract.parameters = struct( ...
    'run', {{}}, ...
    'static', {spec.staticKeys}, ...
    'data', {{}});
spec.contract.requirements = struct();
spec.contract.requirements.roi = struct( ...
    'required', true, ...
    'channelsMin', 2, ...
    'dataSeries', false);
spec.contract.binding = struct( ...
    'scope', 'roi', ...
    'outputScope', 'roi', ...
    'mode', 'channelSlots', ...
    'selectorKeys', {{'instanceChannelName','rawChannelName'}}, ...
    'resolveAt', 'run', ...
    'exactCount', 2, ...
    'outputChannelNameParam', 'outputMaskChannelName');
spec.contract.capabilities = struct( ...
    'preservesRoiList', true, ...
    'roiChannels', true, ...
    'outputsChannels', true, ...
    'roiDataSeries', true, ...
    'outputsDataSeries', true, ...
    'roiMasks', false, ...
