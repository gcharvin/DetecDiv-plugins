    localResourceDef('channel', 'cell_of_interest_mask', 'cell_of_interest', 'outputMaskChannelName', 'channels', 'outputMaskChannelName', false, 'roiChannel'), ...
    localResourceDef('dataSeries', 'division_profile', 'profile', 'profileSeriesName', 'dataSeries', 'profileSeriesName', false, 'roiDataSeries'), ...
    localResourceDef('dataSeries', 'division_score', 'score', 'scoreSeriesName', 'dataSeries', 'scoreSeriesName', false, 'roiDataSeries') ...
    ];
