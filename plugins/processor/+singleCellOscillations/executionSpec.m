    localResourceDef('dataSeries', 'oscillation_trace', 'dataSeries', 'traceOutputName', 'dataSeries', 'traceOutputName', false, 'roiDataSeries'), ...
    localResourceDef('dataSeries', 'normalized_cycles', 'dataSeries', 'normalizedCyclesOutputName', 'dataSeries', 'normalizedCyclesOutputName', false, 'roiDataSeries'), ...
    localResourceDef('dataSeries', 'cycle_metadata', 'dataSeries', 'cycleMetadataOutputName', 'dataSeries', 'cycleMetadataOutputName', false, 'roiDataSeries') ...
    ];
spec.contract.summary = spec.summary;
end

function p = localPortDef(name, type, required, source)
p = struct('name', name, 'type', type, 'required', logical(required), 'source', source);
end

function r = localResourceDef(type, role, symbol, param, port, nameParam, required, transfer)
r = struct( ...
    'type', type, ...
    'role', role, ...
    'symbol', symbol, ...
    'param', param, ...
    'port', port, ...
    'nameParam', nameParam, ...
    'required', logical(required), ...
    'transfer', transfer);
end
